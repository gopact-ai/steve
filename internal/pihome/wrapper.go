package pihome

import "strings"

// Wrapper is the launcher pi-acp starts instead of pi. It runs the real pi
// (STEVE_PI_REAL) without extensions, in the read-only home with an
// explicit tool allowlist. A --session file must resolve, with every link
// and .. followed, into this home's sessions directory; otherwise the
// launcher leaves a note in <home>/refused for Steve, which then starts a
// new session, and exits 3.
func Wrapper(class string) []byte {
	tools := ""
	if class == ReadOnly {
		tools = " --tools " + strings.Join(ReadOnlyTools, ",")
	}
	return []byte(`#!/bin/sh
# generated by steve: pi under the ` + class + ` permission home
real="${STEVE_PI_REAL:-pi}"
home="${PI_CODING_AGENT_DIR:?}"
refuse() {
  mkdir -p "$home/refused" 2>/dev/null && : > "$home/refused/$(basename -- "$1")" 2>/dev/null
  echo "steve: pi session $1 is not in this permission home; it was opened under another policy" >&2
  exit 3
}
sessions="$(cd -P -- "$home" 2>/dev/null && pwd -P)/sessions" || exit 3
previous=""
for arg in "$@"; do
  if [ "$previous" = "--session" ]; then
    case "$arg" in
      /*) ;;
      *) refuse "$arg" ;;
    esac
    case "$arg" in
      */../*|*/..|*/./*|*/.) refuse "$arg" ;;
    esac
    [ -L "$arg" ] && refuse "$arg"
    dir="$(cd -P -- "$(dirname -- "$arg")" 2>/dev/null && pwd -P)" || refuse "$arg"
    case "$dir/" in
      "$sessions"/*) ;;
      *) refuse "$arg" ;;
    esac
  fi
  previous="$arg"
done
exec "$real" "$@" --no-extensions` + tools + "\n")
}

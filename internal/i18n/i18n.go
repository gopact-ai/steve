type Locale string

const (
	LocaleZH Locale = "zh"
	LocaleEN Locale = "en"
)

func FromLang(lang string) Locale {
	lang = strings.ToLower(strings.TrimSpace(lang))
	if cut, _, ok := strings.Cut(lang, "."); ok {
		lang = cut
	}
	if cut, _, ok := strings.Cut(lang, "_"); ok {
		lang = cut
	}
	if cut, _, ok := strings.Cut(lang, "-"); ok {
		lang = cut
	}
	if lang == "en" {
		return LocaleEN
	}
	return LocaleZH
}

